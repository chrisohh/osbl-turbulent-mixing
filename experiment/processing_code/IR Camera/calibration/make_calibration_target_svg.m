function make_calibration_target_svg(boards, outdir, opts)
%MAKE_CALIBRATION_TARGET_SVG  Emit laser-ready SVG for the calibration plates.
%
%   make_calibration_target_svg                    % both boards, this folder
%   make_calibration_target_svg({'coarse'})        % IR board only
%   make_calibration_target_svg([], 'C:\out')      % both, chosen folder
%   make_calibration_target_svg([], [], struct('scale_bar', false))
%   make_calibration_target_svg([], [], struct('fiducials', false))
%
% opts.scale_bar (default true) - 100 mm caliper bar. Recommended to keep:
%   it is the only check that catches the laser rescaling the whole file,
%   which would put the same systematic error into every corner in
%   corners.csv. Costs a 100x3 mm mark in the margin.
% opts.fiducials (default true) - 4 corner crosses, redundant with the
%   plate's own cut outline as a caliper reference. Safe to disable.
%
% Writes raw SVG XML with fprintf. Deliberately NOT print('-dsvg') /
% saveas: MATLAB's figure export goes through the renderer (axes boxes,
% margins, DPI assumptions, PaperPosition scaling) and does not guarantee
% exact physical dimensions. A 0.1% scale error here is a 0.3 mm systematic
% bias across the board, which would sit on top of every measurement made
% through the resulting homography.
%
% The <svg> width/height are given in mm with a matching viewBox, so one
% user unit == one millimetre unambiguously in Inkscape 1.x and in laser
% drivers.
%
% ---------------------------------------------------------------------
% POLARITY WARNING - read before sending to the laser.
% ---------------------------------------------------------------------
% The file is written in LASER polarity, not visual polarity:
%
%   BLACK fill  = ablate  = becomes BRIGHT bare aluminium on the plate
%   no fill     = mask    = stays DARK anodised
%
% So the SVG looks like a photo-negative of the finished plate. This is
% correct: most laser software engraves filled/black regions. Do not
% "fix" the inversion in Inkscape.
%
% The ablated (low-emissivity) squares are the ones the IR camera sees as
% the bright checker cells, because bare aluminium reflects the surrounding
% scene rather than emitting at the plate's own temperature.

if nargin < 1 || isempty(boards)
    boards = {'coarse', 'fine'};
end
if ischar(boards)
    boards = {boards};
end
if nargin < 2 || isempty(outdir)
    outdir = fileparts(mfilename('fullpath'));
    if isempty(outdir)          % running cell-by-cell, mfilename is empty
        outdir = pwd;
    end
end
if nargin < 3 || isempty(opts)
    opts = struct();
end
if ~isfield(opts, 'scale_bar'),  opts.scale_bar  = true; end
if ~isfield(opts, 'fiducials'),  opts.fiducials  = true; end

for k = 1:numel(boards)
    p = calib_target_params(boards{k});
    fpath = fullfile(outdir, sprintf('calib_target_%s.svg', p.name));
    write_svg(p, fpath, opts);

    fprintf('\n=== %s board -> %s ===\n', upper(p.name), fpath);
    fprintf('  Plate        : %.1f x %.1f mm\n', p.plate_w_mm, p.plate_h_mm);
    fprintf('  Squares      : %d x %d @ %.3f mm  (odd x even OK)\n', ...
        p.n_cols, p.n_rows, p.square_mm);
    fprintf('  Pattern      : %.1f x %.1f mm\n', p.board_w_mm, p.board_h_mm);
    fprintf('  Inner corners: %d x %d = %d\n', ...
        p.inner_cols, p.inner_rows, p.n_corners);
    fprintf('  Corner span  : %.1f x %.1f mm\n', ...
        max(p.corner_X) - min(p.corner_X), max(p.corner_Y) - min(p.corner_Y));
    fprintf('  Quiet ring   : %.1f mm\n', p.quiet_mm);
end

fprintf('\nLASER POLARITY: black = ablate = bright bare metal.\n');
fprintf('The SVG is a photo-negative of the finished plate. Do not invert.\n');
if opts.scale_bar
    fprintf('Caliper the 100.000 mm scale bar on the cut plate before trusting it.\n\n');
else
    fprintf('scale_bar disabled - no laser-rescale check on this file. Verify\n');
    fprintf('scale another way (e.g. caliper the plate outline) before trusting it.\n\n');
end
end


% =====================================================================
function write_svg(p, fpath, opts)

fid = fopen(fpath, 'w');
if fid < 0
    error('make_calibration_target_svg:io', 'Cannot write %s', fpath);
end
cleaner = onCleanup(@() fclose(fid));

W = p.plate_w_mm;
H = p.plate_h_mm;

fprintf(fid, '<?xml version="1.0" encoding="UTF-8"?>\n');
fprintf(fid, ['<svg xmlns="http://www.w3.org/2000/svg" ' ...
              'width="%.4gmm" height="%.4gmm" viewBox="0 0 %.4g %.4g">\n'], ...
              W, H, W, H);

% Provenance: everything needed to regenerate or verify this file.
fprintf(fid, '<!--\n');
fprintf(fid, '  Calibration target: %s board\n', p.name);
fprintf(fid, '  Generated by make_calibration_target_svg.m on %s\n', ...
    datestr(now, 'yyyy-mm-dd HH:MM:SS'));
fprintf(fid, '  Plate         : %.4g x %.4g mm\n', W, H);
fprintf(fid, '  Squares       : %d x %d at %.4g mm\n', p.n_cols, p.n_rows, p.square_mm);
fprintf(fid, '  Pattern       : %.4g x %.4g mm at (%.4g, %.4g)\n', ...
    p.board_w_mm, p.board_h_mm, p.board_x0_mm, p.board_y0_mm);
fprintf(fid, '  Inner corners : %d x %d = %d\n', ...
    p.inner_cols, p.inner_rows, p.n_corners);
fprintf(fid, '  1 user unit   = 1 mm\n');
fprintf(fid, '  POLARITY      : black = ABLATE (bright bare Al);\n');
fprintf(fid, '                  unfilled = mask (dark anodise).\n');
fprintf(fid, '                  This file is a photo-negative of the plate.\n');
fprintf(fid, '-->\n');

%% ---- Engrave layer: everything the laser ablates ----
fprintf(fid, '<g id="engrave" inkscape:label="engrave" ');
fprintf(fid, 'inkscape:groupmode="layer" fill="#000000" stroke="none">\n');

% Light checker squares. mod(i+j,2)==0 is ablated.
fprintf(fid, '  <!-- checker squares (ablated) -->\n');
for i = 0:(p.n_cols - 1)
    for j = 0:(p.n_rows - 1)
        if mod(i + j, 2) == 0
            x = p.board_x0_mm + i * p.square_mm;
            y = p.board_y0_mm + j * p.square_mm;
            fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
                x, y, p.square_mm, p.square_mm);
        end
    end
end

% Quiet ring. Standard "white border" convention - the board-boundary
% detector expects the outer light squares to merge into a uniform bright
% surround rather than butting against dark anodise.
q  = p.quiet_mm;
x0 = p.board_x0_mm;  y0 = p.board_y0_mm;
bw = p.board_w_mm;   bh = p.board_h_mm;
fprintf(fid, '  <!-- quiet ring (ablated) -->\n');
fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
    x0 - q, y0 - q, bw + 2*q, q);                       % top
fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
    x0 - q, y0 + bh, bw + 2*q, q);                      % bottom
fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
    x0 - q, y0, q, bh);                                 % left
fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
    x0 + bw, y0, q, bh);                                % right

% Scale-check bar: exactly 100.000 mm outer-edge to outer-edge, with end
% ticks to caliper against. Verifies the laser did not rescale the file.
if opts.scale_bar
    bar_len = 100.0;
    bar_h   = 3.0;
    tick_w  = 1.0;
    tick_h  = 9.0;
    bar_x   = (W - bar_len) / 2;
    bar_y   = y0 + bh + q + max(8, (H - (y0 + bh + q)) / 2 - bar_h);
    if bar_y + tick_h > H - 3      % fall back above the pattern on the strip
        bar_y = max(3, y0 - q - tick_h - 5);
    end
    fprintf(fid, '  <!-- scale check bar: %.3f mm outer edge to outer edge -->\n', bar_len);
    fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
        bar_x, bar_y, bar_len, bar_h);
    fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
        bar_x, bar_y - (tick_h - bar_h)/2, tick_w, tick_h);
    fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
        bar_x + bar_len - tick_w, bar_y - (tick_h - bar_h)/2, tick_w, tick_h);
end

% Corner fiducial crosses, inset 20 mm from the plate corners. Give you
% independent points to caliper the plate against.
if opts.fiducials
    fid_inset = 20.0;
    arm       = 6.0;
    armw      = 1.0;
    fprintf(fid, '  <!-- corner fiducials, %.1f mm inset -->\n', fid_inset);
    for cx = [fid_inset, W - fid_inset]
        for cy = [fid_inset, H - fid_inset]
            fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
                cx - arm, cy - armw/2, 2*arm, armw);
            fprintf(fid, '  <rect x="%.4f" y="%.4f" width="%.4f" height="%.4f"/>\n', ...
                cx - armw/2, cy - arm, armw, 2*arm);
        end
    end
end

fprintf(fid, '</g>\n');

%% ---- Cut layer: plate outline, hairline stroke ----
fprintf(fid, '<g id="cut" inkscape:label="cut" inkscape:groupmode="layer" ');
fprintf(fid, 'fill="none" stroke="#ff0000" stroke-width="0.1">\n');
fprintf(fid, '  <rect x="0.05" y="0.05" width="%.4f" height="%.4f"/>\n', ...
    W - 0.1, H - 0.1);
fprintf(fid, '</g>\n');

fprintf(fid, '</svg>\n');
end
